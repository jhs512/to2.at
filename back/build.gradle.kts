/**
 * Local secrets for `bootRun`, read from a gitignored `back/.env`.
 *
 * Kakao credentials and the Operator password must never reach a tracked file
 * (ADR 0005), and exporting them by hand every time is how they end up pasted
 * somewhere they shouldn't be. `.env.example` documents the keys.
 */
tasks.named<org.springframework.boot.gradle.tasks.run.BootRun>("bootRun") {
    val envFile = file(".env")
    if (envFile.exists()) {
        envFile.readLines()
            .map { it.trim() }
            .filter { it.isNotEmpty() && !it.startsWith("#") && it.contains("=") }
            .forEach { line ->
                val key = line.substringBefore("=").trim()
                val value = line.substringAfter("=").trim().trim('"')
                environment(key, value)
            }
    }
}
